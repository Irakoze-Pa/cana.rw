export type ProductionBatchStatus =
  "Planned" | "Ready" | "In Progress" | "Paused" | "Completed" | "Cancelled";

export interface ProductionOrderSummary {
  _id: string;
  productionOrderNo: string;
  quantity: number;
  unit: string;
  status:
    | "Draft"
    | "Planned"
    | "Released"
    | "In Production"
    | "Completed"
    | "Cancelled"
    | "On Hold";
  plannedDate?: string;
  expectedCompletionDate?: string;
}

export interface ProductSummary {
  _id: string;
  name: string;
  code?: string;
  productCode?: string;
  sku?: string;
  category?: string;
  unit?: string;
  baseUnit?: "kg" | "pcs";
  packSizeKg?: number;
}

export interface FormulaSummary {
  _id: string;
  name: string;
  code?: string;
  formulaCode?: string;
  version: number;
  batchSize?: number;
  batchUnit?: string;
  status?: "Active" | "Inactive";
}

export interface SupervisorSummary {
  _id: string;
  name?: string;
  firstName?: string;
  lastName?: string;
  email?: string;
}

export interface ProductionBatch {
  _id: string;

  batchNo: string;

  /** Present only on historical batches created by the former order workflow. */
  productionOrder?: string | ProductionOrderSummary;

  product: string | ProductSummary;

  productName: string;
  productCode: string;

  outputs?: Array<{
    product: string | ProductSummary;
    productName: string;
    productCode: string;
    plannedQuantity: number;
    actualQuantity: number;
    packSizeKg: number;
    plannedPacks: number;
    actualPacks: number;
    allocatedCost?: number;
    costPerPack?: number;
  }>;

  formula: string | FormulaSummary;

  formulaName: string;
  formulaCode: string;
  formulaVersion: number;
  formulaSnapshot?: Array<{
    rawMaterial: string | { _id?: string };
    rawMaterialName: string;
    rawMaterialCode: string;
    appliesToProduct?: string | { _id?: string; name?: string };
    quantity: number;
    unit: string;
    wastePercentage?: number;
    notes?: string;
  }>;

  plannedQuantity: number;
  actualQuantity: number;

  /** Legacy remaining quantity retained for historical records. */
  remainingQuantity?: number;

  unit: string;

  status: ProductionBatchStatus;

  /**
   * Generated automatically by backend.
   */
  batchNumber: string;

  lotNumber: string;

  startDate?: string;
  endDate?: string;

  supervisor?: string | SupervisorSummary;

  supervisorName: string;

  notes: string;

  /** Timestamp at which this batch's finished output was posted to product stock. */
  finishedGoodsPostedAt?: string;

  actualMaterialCost?: number;
  allocatedLaborCost?: number;
  allocatedEnergyCost?: number;
  allocatedOtherCost?: number;
  totalActualCost?: number;
  costPerKg?: number;
  costPerPack?: number;
  costedAt?: string;
  costingBasis?: "current_supplier_offer" | "actual_issue_cost";
  costPriceAsOf?: string;
  costPriceFallbackMaterials?: string[];
  costFormula?: string | FormulaSummary;
  costFormulaName?: string;
  costFormulaCode?: string;
  costFormulaVersion?: number;
  materialCostLines?: Array<{
    rawMaterial: string | { _id?: string };
    rawMaterialName: string;
    rawMaterialCode: string;
    appliesToProduct?: string | { _id?: string; name?: string };
    quantity: number;
    unit: string;
    unitPrice: number;
    totalCost: number;
    priceSource: "production_issue" | "historical_receipt" | "supplier_offer" | "inventory_average" | "material_setup";
    quantitySource?: "actual_issue" | "pack_output";
    supplier?: string | { _id?: string; name?: string };
    supplierName?: string;
    offerUpdatedAt?: string;
  }>;
  /**
   * Replacement valuation from the latest active formula and current purchase
   * prices. Historical issue-cost fields above remain the accounting record.
   */
  currentMaterialCost?: number;
  currentTotalCost?: number;
  currentCostPerKg?: number;
  currentCostPerPack?: number;
  currentCostedAt?: string;
  currentMaterialCostLines?: Array<{
    rawMaterial: string | { _id?: string };
    rawMaterialName: string;
    rawMaterialCode: string;
    appliesToProduct?: string | { _id?: string; name?: string };
    quantity: number;
    unit: string;
    unitPrice: number;
    totalCost: number;
    priceSource: "supplier_offer" | "inventory_average" | "material_setup";
    supplier?: string | { _id?: string; name?: string };
    supplierName?: string;
    offerUpdatedAt?: string;
  }>;

  createdAt: string;
  updatedAt: string;
}

export interface CreateProductionBatchData {
  /** Select product and formula to create a batch directly. */
  product?: string;
  formula?: string;

  /**
   * Optional.
   * Backend defaults to the remaining quantity.
   */
  plannedQuantity?: number;

  unit?: string;

  /**
   * Create status is controlled by backend.
   * Keep optional for compatibility.
   */
  status?: ProductionBatchStatus;

  /**
   * Batch number is generated by backend.
   */
  batchNumber?: string;

  lotNumber?: string;

  /**
   * Optional production start date.
   */
  startDate?: string | Date;

  supervisor?: string;

  supervisorName?: string;

  notes?: string;
}

export interface UpdateProductionBatchData {
  plannedQuantity?: number;

  actualQuantity?: number;

  unit?: string;

  status?: ProductionBatchStatus;

  batchNumber?: string;

  lotNumber?: string;

  startDate?: string | Date;

  endDate?: string | Date;

  supervisor?: string;

  supervisorName?: string;

  notes?: string;
}

export interface ProductionBatchStats {
  total: number;
  planned: number;
  ready: number;
  inProgress: number;
  paused: number;
  completed: number;
  cancelled: number;
}
